const PHOTO_BASE = 'https://picsum.photos/seed';

function photos(visitId, locationId, seeds) {
  return seeds.map((seed, i) => ({
    id: `${visitId}-p${i + 1}`,
    visitId,
    locationId,
    url: `${PHOTO_BASE}/${seed}/1200/900`,
    thumbnailUrl: `${PHOTO_BASE}/${seed}/400/300`,
    filename: `img_${seed}.jpg`,
    originalName: `DSC_${seed}.jpg`,
    mimeType: 'image/jpeg',
    sizeBytes: Math.floor(Math.random() * 3000000) + 1000000,
    uploadedAt: new Date().toISOString(),
  }));
}

